// Renders the confirmation-email header (GDG logo, wordmark, color bar, pills, "You're on the list!")
// to a PNG with the brand font, and writes it as a base64 module the email embeds as an inline image.
// Images keep their colors in Gmail iOS dark mode and their font in every client, unlike HTML text.
//
// Usage: node scripts/render-email-header.mjs
// Needs Google Chrome (override the path with CHROME_PATH). Re-run after changing the header design.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import sharp from "sharp";

const root = resolve(import.meta.dirname, "..");
const chrome = process.env.CHROME_PATH ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";

// CSS pixels; rendered at 2x for sharp text on high-density screens.
const WIDTH = 480;
const HEIGHT = 290;
const SCALE = 2;

const fontUrl = pathToFileURL(join(root, "lib/emails/assets/Outfit-latin.woff2")).href;
const logoUrl = pathToFileURL(join(root, "public/gdg-cloud-pune-logo.png")).href;

const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8">
    <style>
      @font-face { font-family: Outfit; src: url("${fontUrl}") format("woff2"); font-weight: 100 900; }
      html, body { margin: 0; background: #1e1e1e; }
      .header { box-sizing: border-box; width: ${WIDTH}px; height: ${HEIGHT}px; padding-top: 2px; font-family: Outfit; color: #f0f0f0; -webkit-font-smoothing: antialiased; }
      .logo { display: block; width: 240px; height: auto; }
      .wordmark { margin-top: 26px; font-size: 46px; font-weight: 700; line-height: 0.92; letter-spacing: -0.03em; }
      .bar { display: flex; gap: 8px; width: 320px; height: 12px; margin-top: 18px; }
      .bar span { flex: 1; border: 2.5px solid #f0f0f0; border-radius: 999px; }
      .pills { display: flex; gap: 8px; margin-top: 16px; }
      .pill { padding: 6px 14px; font-size: 16px; font-weight: 500; line-height: 1; border: 2.5px solid #f0f0f0; border-radius: 999px; }
      .solid { font-weight: 600; color: #1e1e1e; background: #f0f0f0; }
      .done { margin-top: 26px; font-size: 32px; font-weight: 700; line-height: 1; letter-spacing: -0.02em; color: #f9ab00; }
    </style>
  </head>
  <body>
    <div class="header">
      <img class="logo" src="${logoUrl}" alt="">
      <div class="wordmark">Cloud<br>Community Day</div>
      <div class="bar">
        <span style="background:#4285f4"></span><span style="background:#34a853"></span><span style="background:#f9ab00"></span><span style="background:#ea4335"></span>
      </div>
      <div class="pills"><span class="pill">Pune</span><span class="pill solid">2026</span></div>
      <div class="done">You&rsquo;re on the list!</div>
    </div>
  </body>
</html>`;

const workDir = mkdtempSync(join(tmpdir(), "email-header-"));
const htmlPath = join(workDir, "header.html");
const pngPath = join(workDir, "header.png");
writeFileSync(htmlPath, html);

execFileSync(chrome, [
  "--headless=new",
  "--disable-gpu",
  "--hide-scrollbars",
  "--allow-file-access-from-files",
  `--force-device-scale-factor=${SCALE}`,
  `--window-size=${WIDTH},${HEIGHT}`,
  "--virtual-time-budget=3000",
  `--screenshot=${pngPath}`,
  pathToFileURL(htmlPath).href,
], { stdio: "pipe" });

// Chrome's screenshot is a full-colour PNG (~47KB). The artwork is flat colours and text, so a 256-colour
// palette PNG is visually identical at under half the size. PNG (not WebP) because Outlook desktop and
// some other email clients don't display WebP. `sharp` ships with Next.js.
const rawPng = readFileSync(pngPath);
const png = await sharp(rawPng)
  .png({ palette: true, colors: 256, quality: 100, dither: 0, compressionLevel: 9, effort: 10 })
  .toBuffer();
const outFile = join(root, "lib/emails/header-image.ts");
writeFileSync(
  outFile,
  `// Generated by scripts/render-email-header.mjs — do not edit by hand.
export const EMAIL_HEADER_CID = "ccd-email-header";
export const EMAIL_HEADER_WIDTH = ${WIDTH};
export const EMAIL_HEADER_HEIGHT = ${HEIGHT};
export const EMAIL_HEADER_PNG_BASE64 =
  "${png.toString("base64")}";
`,
);

console.log(`Rendered ${pngPath} (${png.length} bytes) -> ${outFile}`);
